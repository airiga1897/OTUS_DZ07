"""The supported Selectel module operations, without a runtime registry."""

from __future__ import annotations

from collections.abc import Mapping
from pathlib import Path
from typing import TYPE_CHECKING, Protocol

if TYPE_CHECKING:
    from cloud_contract import InfrastructureResult, StandDescription
    from plan_diagnostics import PlannedResource
    from runtime_ports import ConfigurationPort, FilePort, RootPort, StagedControllerPort
    from selectel_reports import EmptyNamespaceAudit
    from selectel_staged import Backend
    from selectel_staged_audit import PageClient
    from stage_store import StageStore


class SelectelFunctions(Protocol):
    def sequential_enabled(self, root: Path) -> bool: ...
    def staged_backend(self, api: StagedControllerPort, cleanup: bool = False) -> Backend: ...
    def reject_shared_namespace(self, api: FilePort) -> None: ...
    def audit_empty_stages(self, api: FilePort) -> EmptyNamespaceAudit: ...
    def recover_stages(self, api: FilePort, error: BaseException) -> None: ...
    def validate_staged_local(
        self, api: RootPort, result: InfrastructureResult, journal: Mapping[str, object], store: StageStore
    ) -> None: ...
    def binding(self, config: dict[str, str], namespace: str, zone: str | None) -> dict[str, object]: ...
    def partial_state_binding(self, root: Path, config: dict[str, str], prefix: str) -> dict[str, object]: ...
    def validate_managed_state(self, state: dict[str, object], config: dict[str, str], prefix: str) -> None: ...
    def validate_node_creation(self, change: PlannedResource, allowed: set[str]) -> None: ...
    def check_network(
        self, cloud: PageClient, result: InfrastructureResult, admin_cidrs: list[str]
    ) -> dict[str, bool]: ...
    def check_placement(self, api: ConfigurationPort, lab: StandDescription) -> None: ...
    def reject_cloud_resources(self, api: FilePort, cloud: PageClient) -> None: ...
